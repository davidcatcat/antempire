/**
 * Code SHA-256 of the P0-A2 world as run by the experiment Worker (part of its rules fingerprint): the transitive
 * RUNTIME import graph (type-only imports excluded) of prototypes/continuous-world/worker/p0a2-world.ts, TypeScript
 * files only (params.json is covered by its own SHA-256 in the fingerprint), excluding the generated constant file.
 * A save made under other code is refused on load (FINGERPRINT_MISMATCH) — any edit of decision.ts, world.ts, … changes
 * this hash. Node tool (not part of the Worker graph); tests/worker-runtime.test.ts fails when the constant is stale.
 *   node prototypes/continuous-world/tools/p0a2-code-hash.ts           print
 *   node prototypes/continuous-world/tools/p0a2-code-hash.ts --write   regenerate the generated constant files
 *
 * The opt-in colony-members CANDIDATE world (p0a2-colony-world.ts, save world kind p0a2-colony-v1) has its own
 * generated files, written by the same --write (tests/p0a2-colony-world.test.ts fails when they are stale):
 *  - worker/p0a2-colony-scenario.ts: the sampling rules the candidate uses, extracted from the candidate scenario
 *    scenarios/day0-budding-candidate.json, with the checksum of the WHOLE scenario file (the Worker does not bundle
 *    the scenario's prose);
 *  - worker/p0a2-colony-code-hash.ts: the code hash over the candidate's own import graph (which contains the whole
 *    default graph).
 * The default world's graph and hash do not depend on either file.
 */
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { SCENARIO_CHECKSUM_ALGORITHM, scenarioChecksum } from '../../../engine/day0/founding-sampler.ts';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..', '..');
export const ENTRY = 'prototypes/continuous-world/worker/p0a2-world.ts';
export const CONST_FILE = 'prototypes/continuous-world/worker/p0a2-code-hash.ts';
export const COLONY_ENTRY = 'prototypes/continuous-world/worker/p0a2-colony-world.ts';
export const COLONY_CONST_FILE = 'prototypes/continuous-world/worker/p0a2-colony-code-hash.ts';
export const COLONY_SCENARIO_FILE = 'scenarios/day0-budding-candidate.json';
export const COLONY_SCENARIO_CONST_FILE = 'prototypes/continuous-world/worker/p0a2-colony-scenario.ts';
/** generated constant files that hold code hashes: never part of a code hash */
const HASH_CONST_FILES = [CONST_FILE, COLONY_CONST_FILE];
const strip = (s: string) => s.replace(/\/\*[\s\S]*?\*\//g, '').replace(/(^|[^:\\])\/\/.*$/gm, '$1');

/** runtime import specifiers (import … from / export … from / side-effect imports; `import type` / `export type` skipped) */
export function runtimeSpecifiers(src: string): string[] {
  const s = strip(src), out: string[] = [];
  for (const m of s.matchAll(/\b(import|export)\s+(type\s+)?[^'"`;]*?\bfrom\s*(['"])([^'"]+)\3/g)) if (!m[2]) out.push(m[4]);
  for (const m of s.matchAll(/\bimport\s*(['"])([^'"]+)\1/g)) out.push(m[2]);
  return out;
}

/** the files whose content makes up the code hash of `entry` (repo-relative, sorted) */
export function codeFiles(root = ROOT, entry = ENTRY): string[] {
  const seen = new Set<string>(), q = [entry];
  while (q.length) {
    const f = q.shift()!; if (seen.has(f)) continue; seen.add(f);
    for (const spec of runtimeSpecifiers(fs.readFileSync(path.join(root, f), 'utf8'))) {
      if (!spec.startsWith('.')) throw Error(`${f}: non-relative import ${spec}`);
      const t = path.posix.normalize(path.posix.join(path.posix.dirname(f), spec));
      if (t.endsWith('.ts') && !HASH_CONST_FILES.includes(t)) q.push(t);
    }
  }
  return [...seen].sort();
}
export function codeHash(root = ROOT, entry = ENTRY): { files: string[]; sha256: string } {
  const files = codeFiles(root, entry), h = crypto.createHash('sha256');
  for (const f of files) { h.update(f); h.update('\0'); h.update(fs.readFileSync(path.join(root, f))); h.update('\0'); }
  return { files, sha256: h.digest('hex') };
}
export const constFileText = (c: { files: string[]; sha256: string }) => `/**
 * GENERATED by prototypes/continuous-world/tools/p0a2-code-hash.ts --write — do not edit by hand.
 * SHA-256 over (path, content) of every TypeScript module the P0-A2 experiment world runs (runtime import graph of
 * p0a2-world.ts). Part of the P0-A2 rules fingerprint: a snapshot made under other code is refused on restore.
 * tests/worker-runtime.test.ts fails when this is stale.
 */
export const P0A2_CODE_SHA256 = '${c.sha256}';
export const P0A2_CODE_FILES: readonly string[] = ${JSON.stringify(c.files, null, 2).replace(/"/g, "'")};
`;
export const colonyConstFileText = (c: { files: string[]; sha256: string }) => `/**
 * GENERATED by prototypes/continuous-world/tools/p0a2-code-hash.ts --write — do not edit by hand.
 * SHA-256 over (path, content) of every TypeScript module the P0-A2 colony-members CANDIDATE world runs (runtime import
 * graph of p0a2-colony-world.ts; it contains the default P0-A2 graph). Part of the candidate's rules fingerprint.
 * tests/p0a2-colony-world.test.ts fails when this is stale.
 */
export const P0A2_COLONY_CODE_SHA256 = '${c.sha256}';
export const P0A2_COLONY_CODE_FILES: readonly string[] = ${JSON.stringify(c.files, null, 2).replace(/"/g, "'")};
`;

/** the scenario fields the colony candidate samples (default variant: each field's own spec, brood = the scenario's
 *  pre-registered default level). A field the scenario does not have is null (the candidate then uses none of it). */
export const COLONY_SCENARIO_FIELDS = ['queens', 'minor_workers', 'major_fraction', 'eggs_per_minor', 'larvae_per_minor', 'pupae_per_minor', 'carried_brood_progress'] as const;
type Any = any; // eslint-disable-line @typescript-eslint/no-explicit-any -- tagged scenario JSON
export function colonyScenarioExtract(root = ROOT): Record<string, unknown> {
  const sc: Any = JSON.parse(fs.readFileSync(path.join(root, COLONY_SCENARIO_FILE), 'utf8'));
  const spec = (k: string): Record<string, unknown> | null => {
    const f = sc.fields?.[k]; if (!f) return null;
    const out: Record<string, unknown> = { distribution: f.distribution };
    for (const p of ['value', 'min', 'max'] as const) if (typeof f[p] === 'number') out[p] = f[p];
    return out;
  };
  return {
    file: COLONY_SCENARIO_FILE, id: sc.id, schema: sc.schema, status: sc.status, activated: sc.activation.activated,
    checksum: scenarioChecksum(sc), checksum_algorithm: SCENARIO_CHECKSUM_ALGORITHM,
    prng: { id: sc.sampling.prng.id, stream_namespace: sc.sampling.prng.stream_namespace },
    order: sc.sampling.order, brood_level: sc.scenario_variants.brood.default_level,
    major_fraction_isolated: sc.fields?.major_fraction?.isolated === true,
    fields: Object.fromEntries(COLONY_SCENARIO_FIELDS.map((k) => [k, spec(k)])),
  };
}
export const colonyScenarioFileText = (x: Record<string, unknown>) => `/**
 * GENERATED by prototypes/continuous-world/tools/p0a2-code-hash.ts --write — do not edit by hand.
 * The sampling rules the P0-A2 colony-members CANDIDATE world uses, extracted from the candidate scenario
 * ${COLONY_SCENARIO_FILE} (Owner #202 provisional experiment specification — NOT the #201 GO): ids, PRNG, sampling
 * order, the default-variant distribution of each sampled field and the checksum of the WHOLE scenario file.
 * No number is defined here: every value is copied from the scenario. tests/p0a2-colony-world.test.ts fails when this
 * is stale and checks that the candidate's draws equal engine/day0/founding-sampler.ts on the full scenario.
 */
export const COLONY_SCENARIO = ${JSON.stringify(x, null, 2)} as const;
`;

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const write = process.argv.includes('--write');
  if (write) fs.writeFileSync(path.join(ROOT, COLONY_SCENARIO_CONST_FILE), colonyScenarioFileText(colonyScenarioExtract()));
  const c = codeHash(), k = codeHash(ROOT, COLONY_ENTRY);
  if (write) { fs.writeFileSync(path.join(ROOT, CONST_FILE), constFileText(c)); fs.writeFileSync(path.join(ROOT, COLONY_CONST_FILE), colonyConstFileText(k)); }
  console.log(JSON.stringify({ ...c, colony: k }, null, 1));
}
