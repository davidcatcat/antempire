/**
 * Code SHA-256 of the P0-A2 world as run by the experiment Worker (part of its rules fingerprint): the transitive
 * RUNTIME import graph (type-only imports excluded) of prototypes/continuous-world/worker/p0a2-world.ts, TypeScript
 * files only (params.json is covered by its own SHA-256 in the fingerprint), excluding the generated constant file.
 * A save made under other code is refused on load (FINGERPRINT_MISMATCH) — any edit of decision.ts, world.ts, … changes
 * this hash. Node tool (not part of the Worker graph); tests/worker-runtime.test.ts fails when the constant is stale.
 *   node prototypes/continuous-world/tools/p0a2-code-hash.ts           print
 *   node prototypes/continuous-world/tools/p0a2-code-hash.ts --write   regenerate worker/p0a2-code-hash.ts
 */
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..', '..');
export const ENTRY = 'prototypes/continuous-world/worker/p0a2-world.ts';
export const CONST_FILE = 'prototypes/continuous-world/worker/p0a2-code-hash.ts';
const strip = (s: string) => s.replace(/\/\*[\s\S]*?\*\//g, '').replace(/(^|[^:\\])\/\/.*$/gm, '$1');

/** runtime import specifiers (import … from / export … from / side-effect imports; `import type` / `export type` skipped) */
export function runtimeSpecifiers(src: string): string[] {
  const s = strip(src), out: string[] = [];
  for (const m of s.matchAll(/\b(import|export)\s+(type\s+)?[^'"`;]*?\bfrom\s*(['"])([^'"]+)\3/g)) if (!m[2]) out.push(m[4]);
  for (const m of s.matchAll(/\bimport\s*(['"])([^'"]+)\1/g)) out.push(m[2]);
  return out;
}

/** the files whose content makes up the code hash (repo-relative, sorted) */
export function codeFiles(root = ROOT): string[] {
  const seen = new Set<string>(), q = [ENTRY];
  while (q.length) {
    const f = q.shift()!; if (seen.has(f)) continue; seen.add(f);
    for (const spec of runtimeSpecifiers(fs.readFileSync(path.join(root, f), 'utf8'))) {
      if (!spec.startsWith('.')) throw Error(`${f}: non-relative import ${spec}`);
      const t = path.posix.normalize(path.posix.join(path.posix.dirname(f), spec));
      if (t.endsWith('.ts') && t !== CONST_FILE) q.push(t);
    }
  }
  return [...seen].sort();
}
export function codeHash(root = ROOT): { files: string[]; sha256: string } {
  const files = codeFiles(root), h = crypto.createHash('sha256');
  for (const f of files) { h.update(f); h.update('\0'); h.update(fs.readFileSync(path.join(root, f))); h.update('\0'); }
  return { files, sha256: h.digest('hex') };
}
export const constFileText = (c: { files: string[]; sha256: string }) => `/**
 * GENERATED by prototypes/continuous-world/tools/p0a2-code-hash.ts --write — do not edit by hand.
 * SHA-256 over (path, content) of every TypeScript module the P0-A2 experiment world runs (runtime import graph of
 * p0a2-world.ts). Part of the P0-A2 rules fingerprint: a snapshot made under other code is refused on restore.
 * tests/worker-runtime.test.ts fails when this is stale.
 */
export const P0A2_CODE_SHA256 = '${c.sha256}';
export const P0A2_CODE_FILES: readonly string[] = ${JSON.stringify(c.files, null, 2).replace(/"/g, "'")};
`;

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const c = codeHash();
  if (process.argv.includes('--write')) fs.writeFileSync(path.join(ROOT, CONST_FILE), constFileText(c));
  console.log(JSON.stringify(c, null, 1));
}
