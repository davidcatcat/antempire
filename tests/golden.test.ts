/**
 * GOLDEN TEST (byte-for-byte) for the CURRENT rules version (RULES_TAG, now v7 = v2-review.7).
 *  1. Regenerates the 20-seed winter report and the single-seed report into a temporary directory and
 *     compares every file BYTE-FOR-BYTE with reports/day15-134-<tag>-*.
 *  2. Replays 28 scenarios and compares the hash chain of the FULL daily output (summary + events + state)
 *     with tests/golden/<tag>-trace-sha256.json.
 * A pure refactor must keep both identical. Changing them is a rules update (separate PR).
 * History: reports/day15-134-v6-* and tests/golden/v6-trace-sha256.json pin the v6 engine; the v6 -> v7
 * difference is proven to be ONLY the nest-temperature memory by tests/differential.test.ts.
 */
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { generateWinterMultiseed, RULES_TAG } from '../cli/reports/winter-multiseed.ts';
import { generateSingleSeed120 } from '../cli/reports/single-seed-120.ts';
import { REPO_ROOT, readJson } from '../cli/lib/load.ts';
import { ENGINE_VERSION } from '../engine/index.ts';
import { SCENARIOS } from './lib/scenarios.ts';
import { traceScenario } from './lib/trace.ts';

const failures: string[] = [], results: Record<string, string> = {}, tag = RULES_TAG;
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'antempire-golden-'));
try {
  generateWinterMultiseed(tmp); generateSingleSeed120(tmp);
  for (const f of [`day15-134-${tag}-20seeds-daily.csv`, `day15-134-${tag}-20seeds-weekly.csv`, `day15-134-${tag}-20seeds-analysis.json`, `day15-134-${tag}-daily.csv`, `day15-134-${tag}-weekly.csv`, `day15-134-${tag}-analysis.json`]) {
    const committed = path.join(REPO_ROOT, 'reports', f);
    const same = fs.existsSync(committed) && Buffer.compare(fs.readFileSync(path.join(tmp, f)), fs.readFileSync(committed)) === 0;
    results['reports/' + f] = same ? 'byte-identical' : 'DIFFERENT';
    if (!same) failures.push('reports/' + f);
  }
} finally { fs.rmSync(tmp, { recursive: true, force: true }); }

const golden = readJson(`tests/golden/${tag}-trace-sha256.json`);
if (golden.generated_from.engine_version !== ENGINE_VERSION) failures.push(`golden trace was generated by ${golden.generated_from.engine_version}, engine is ${ENGINE_VERSION}`);
for (const sc of SCENARIOS) {
  const got = traceScenario(sc), expected = golden.scenarios[sc.name];
  const same = !!expected && expected.sha256 === got.sha256 && expected.final_day === got.final_day;
  results['trace/' + sc.name] = same ? `identical (${sc.days} days)` : `DIFFERENT expected ${expected?.sha256} got ${got.sha256}`;
  if (!same) failures.push('trace/' + sc.name);
}
if (Object.keys(golden.scenarios).length !== SCENARIOS.length) failures.push('scenario count mismatch with golden file');
console.log(JSON.stringify({ passed: failures.length === 0, rules_tag: tag, engine_version: ENGINE_VERSION, compared: Object.keys(results).length, failures, results }, null, 2));
if (failures.length) process.exitCode = 1;
